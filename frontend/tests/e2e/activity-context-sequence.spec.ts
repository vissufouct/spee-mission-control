import { expect, test } from '@playwright/test'

for (const example of [1, 2]) {
  test(`contexto mostra blocos e preserva o progresso do exemplo ${example}`, async ({ page }, info) => {
    await page.goto(`/estudante/percurso/actividades/registar-empresa?exemplo=${example}`)
    const context = page.getByRole('region', { name: 'Blocos em contexto' })
    const cards = context.locator('.student-context-card')
    await expect(cards).toHaveCount(3)
    await expect(cards.nth(0).getByRole('button', { name: 'Ver bloco: Ideação', exact: true })).toBeEnabled()
    await expect(cards.nth(1)).toContainText('Bloco seleccionado')
    await expect(cards.nth(1).getByRole('button', { name: 'Ver bloco: Criação de empresas', exact: true })).toBeEnabled()
    await expect(cards.nth(2).getByRole('button', { name: 'Ver bloco: Início de actividades', exact: true })).toBeEnabled()
    await expect(cards.nth(0)).toContainText(`${example === 1 ? 4 : 0} de 4 actividades concluídas`)
    await expect(cards.nth(1).getByLabel(`${example === 1 ? 4 : 0} de 7 tarefas concluídas`)).toBeVisible()
    await expect(cards.nth(1).getByRole('progressbar')).toHaveAttribute('aria-valuemax', '3')
    await cards.nth(0).getByRole('button', { name: 'Ver bloco: Ideação', exact: true }).click()
    await expect(page).toHaveURL(/percurso\?bloco=ideacao$/)
    await page.getByRole('button', { name: 'Ver tarefas: Encontrar uma ideia de negócio', exact: true }).click()
    await expect(cards.nth(1).getByRole('button', { name: 'Ver bloco: Ideação', exact: true })).toBeVisible()
    await expect(cards.nth(2)).toContainText('Criação de empresas')
    await page.goto('/estudante/percurso/actividades/boas-vindas')
    await expect(cards).toHaveCount(3)
    await expect(cards.nth(0)).toContainText('Este é o primeiro bloco do roteiro.')
    await expect(cards.nth(0).getByRole('button')).toHaveCount(0)
    await page.goto('/estudante/percurso/actividades/orientacao-final')
    await expect(cards).toHaveCount(3)
    await expect(cards.nth(2)).toContainText('Primeiro ano fiscal')
    await expect(cards.nth(2)).toContainText('Brevemente')
    await expect(cards.nth(2).getByRole('progressbar')).toHaveCount(0)
    await cards.nth(2).getByRole('button', { name: 'Ver bloco: Primeiro ano fiscal' }).click()
    await expect(page).toHaveURL(/percurso\?bloco=primeiro-ano$/)
    await page.getByRole('button', { name: 'Voltar para o bloco actual' }).click()
    await expect(page).toHaveURL(new RegExp(`bloco=${example === 1 ? 'constituicao' : 'acolhimento'}$`))
    await page.goto('/estudante/percurso/actividades/registar-empresa')
    await expect(cards.nth(1).getByLabel(`${example === 1 ? 4 : 0} de 7 tarefas concluídas`)).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`contexto-blocos-exemplo-${example}.png`), fullPage: true })
  })
}

test('contexto funciona sem AppShell e apresenta o fim do roteiro sem ligação fictícia', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-contexto-da-actividade--selected&viewMode=story')
  const context = page.getByRole('region', { name: 'Blocos em contexto' })
  await expect(context.locator('.student-context-card')).toHaveCount(3)
  await expect(page.getByText('Simulador Empresarial', { exact: true })).toHaveCount(0)
  await expect(context.locator('.student-context-card').nth(0)).toContainText('Concluído')
  await expect(context.locator('.student-context-card').nth(1)).toContainText('Em curso')
  await expect(context.getByRole('button', { name: 'Ver bloco: Criação de empresas' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('contexto-blocos-sem-shell.png'), fullPage: true })
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-contexto-da-actividade--last-block&viewMode=story')
  await expect(context.locator('.student-context-card').nth(2)).toContainText('Este é o último bloco do roteiro.')
  await expect(context.locator('.student-context-card').nth(2).getByRole('button')).toHaveCount(0)
})
