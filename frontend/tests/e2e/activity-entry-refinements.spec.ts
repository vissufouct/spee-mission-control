import { expect, test } from '@playwright/test'

test('três cartões alinhados, actividade nas mensagens, participantes e acções', async ({ page }, info) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/estudante/percurso/actividades/registar-empresa')
  const tiles = page.locator('.student-notification-tile')
  await expect(tiles).toHaveCount(3)
  await expect(tiles.nth(1)).toContainText('Registar empresa')
  const boxes = await tiles.evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().top))
  expect(Math.max(...boxes) - Math.min(...boxes)).toBeLessThan(2)
  const participants = page.getByRole('region', { name: 'Participantes da actividade' })
  await expect(participants.getByText('Dados simulados')).toBeVisible()
  await expect(participants.getByRole('listitem')).toHaveCount(3)
  await expect(participants).toContainText('Ana Machava')
  const context = page.getByRole('region', { name: 'Actividades em contexto' })
  await expect(context.getByRole('button', { name: 'Ver: Reserva do nome', exact: true })).toBeEnabled()
  await expect(context.getByRole('button', { name: 'Iniciar actividade: Convidar sócios', exact: true })).toBeEnabled()
  await expect(context.getByRole('button', { name: 'Ver: Início de actividades', exact: true })).toBeEnabled()
  const materials = page.locator('details[aria-label="Materiais de apoio"]')
  await expect(materials.locator('summary')).toContainText('Página Web (2)')
  await expect(materials).not.toHaveAttribute('open', '')
  await materials.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(materials.getByRole('link', { name: /Guia de registo/ })).toBeVisible()
  await materials.locator('summary').click()
  await expect(materials.getByRole('link', { name: /Guia de registo/ })).not.toBeVisible()
  await page.screenshot({ path: info.outputPath('activity-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('activity-mobile.png'), fullPage: true })
  await context.getByRole('button', { name: 'Continuar actividade: Registar empresa', exact: true }).click()
  await expect(page).toHaveURL(/percurso\/registar-empresa$/)
})

test('introdução pode ser fechada sem entrar e funciona em mobile', async ({ page }, info) => {
  await page.goto('/')
  const teacher = page.getByRole('button', { name: /Mission Control do Docente/ })
  await teacher.click()
  await expect(page.getByRole('dialog')).toContainText('não são visíveis ao docente')
  await page.screenshot({ path: info.outputPath('introduction-desktop.png') })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(teacher).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /Mission Control do Estudante/ }).click()
  await expect(page.getByRole('dialog')).toContainText('o canal do grupo permanece privado')
  await page.getByRole('link', { name: 'Entrar', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('introduction-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Voltar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/\/$/)
})
