import { expect, test } from './legacy-fixture'

test('três cartões alinhados, actividade nas mensagens, participantes e acções', async ({ page }, info) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/estudante/percurso/actividades/registar-empresa')
  const notifications = page.locator('.student-notification-launcher')
  await expect(notifications.getByLabel('4 notificações pendentes no total')).toHaveText('4')
  await notifications.press('Enter')
  await page.getByRole('tab', { name: 'Actividade 1', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Registar empresa')
  await page.keyboard.press('Escape')
  const tasks = page.getByRole('region', { name: 'Tarefas da actividade' })
  await expect(tasks.locator('.student-task-columns')).toHaveText('TarefaParticipantesEstadoAcção')
  // Legacy scenarios without task participation never inherit the whole activity team.
  await expect(tasks.getByRole('region', { name: 'Participantes: Preencher os dados da empresa' })).toContainText('—')
  await expect(page.locator('.student-context-card').getByText('Participantes:', { exact: false })).toHaveCount(0)
  await expect(page.locator('.student-next-activity')).toContainText('Próxima tarefa: Pré-quiz de registo da empresa')
  const context = page.getByRole('region', { name: 'Blocos em contexto' })
  await expect(context.getByRole('button', { name: 'Ver bloco: Ideação', exact: true })).toBeEnabled()
  await expect(context.getByRole('button', { name: 'Ver bloco: Constituição', exact: true })).toBeEnabled()
  await expect(context.getByRole('button', { name: 'Ver bloco: Primeiro ano fiscal', exact: true })).toBeEnabled()
  await expect(context.locator('.student-context-card')).toHaveCount(3)
  await expect(context.getByRole('button', { name: 'Convidar sócios', exact: true })).toHaveCount(0)
  const materials = page.locator('details[aria-label="Materiais de apoio"]')
  await expect(materials.locator('summary')).toContainText('Página Web (2)')
  await expect(materials).not.toHaveAttribute('open', '')
  await materials.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(materials.getByRole('link', { name: /Guia de registo/ })).toBeVisible()
  await materials.locator('summary').click()
  await expect(materials.getByRole('link', { name: /Guia de registo/ })).not.toBeVisible()
  await page.screenshot({ path: info.outputPath('activity-desktop.png'), fullPage: true })
  await page.screenshot({ path: info.outputPath('activity-desktop-collapsed.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('activity-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Continuar tarefa: Submeter o formulário de registo', exact: true }).click()
  await expect(page).toHaveURL(/percurso\/registar-empresa$/)
})

test('introdução pode ser fechada sem entrar e funciona em mobile', async ({ page }, info) => {
  await page.goto('/')
  const teacher = page.getByRole('button', { name: /Painel do Docente/ })
  await teacher.click()
  await expect(page.getByRole('dialog')).toContainText('não são visíveis ao docente')
  await page.screenshot({ path: info.outputPath('introduction-desktop.png') })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(teacher).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /Painel do Estudante/ }).click()
  await expect(page.getByRole('dialog')).toContainText('o canal do grupo permanece privado')
  await page.getByRole('link', { name: /Entrar no exemplo 2/ }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('introduction-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Voltar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/\/$/)
})
