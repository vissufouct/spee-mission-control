import { expect, test } from '@playwright/test'

test('resumo integrado do bloco em grelha 2 × 2', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/estudante/percurso?bloco=constituicao')
  const notifications = page.locator('.student-notification-launcher')
  await expect(notifications.getByLabel('3 notificações pendentes no total')).toHaveText('3')
  await notifications.press('Enter')
  await expect(page.getByRole('tab', { name: 'Grupo 1', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  const summary = page.getByRole('region', { name: 'Resumo do bloco' })
  const panel = page.getByRole('region', { name: 'Bloco e actividades: Constituição', exact: true })
  await expect(panel.getByRole('region', { name: 'Resumo do bloco' })).toBeVisible()
  await expect(panel.getByRole('region', { name: 'Actividades deste bloco', exact: true })).toBeVisible()
  await expect(panel.locator('.spee-panel')).toHaveCount(0)
  await panel.getByRole('button', { name: 'Concluídas', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Ver Reserva do nome', exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Continuar Registar empresa', exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Todas', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Continuar Registar empresa', exact: true })).toBeVisible()
  await expect(summary).toHaveCount(1)
  await expect(summary.getByRole('listitem')).toHaveCount(4)
  await expect(summary).toContainText('1 concluída')
  await expect(summary).toContainText('1 em curso')
  await expect(summary).toContainText('1 por iniciar')
  await expect(summary).toContainText('1 bloqueada')
  await expect(page.getByText('Algumas actividades podem decorrer em paralelo.')).toHaveCount(0)
  const checkGrid = async () => {
    const boxes = await summary.getByRole('listitem').evaluateAll(nodes => nodes.map(node => { const b = node.getBoundingClientRect(); return { x: b.x, y: b.y } }))
    expect(boxes[0].y).toBe(boxes[1].y)
    expect(boxes[2].y).toBe(boxes[3].y)
    expect(boxes[0].x).toBe(boxes[2].x)
    expect(boxes[1].x).toBe(boxes[3].x)
    expect(boxes[2].y).toBeGreaterThan(boxes[0].y)
  }
  await checkGrid()
  const checkAlignment = async () => {
    const indicators = await summary.boundingBox()
    const title = await panel.getByRole('heading', { name: 'Constituição', exact: true }).boundingBox()
    const progress = await panel.getByRole('progressbar', { name: 'Progresso do bloco' }).boundingBox()
    expect(progress!.x + progress!.width).toBeLessThan(indicators!.x)
    expect(indicators!.y).toBeGreaterThanOrEqual(title!.y)
    expect(indicators!.y + indicators!.height).toBeLessThanOrEqual(progress!.y + progress!.height)
  }
  await checkAlignment()
  await page.screenshot({ path: info.outputPath('block-summary-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 720, height: 853 })
  await checkAlignment()
  await page.screenshot({ path: info.outputPath('block-summary-tablet.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await checkGrid()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('block-summary-mobile.png'), fullPage: true })
  await page.getByRole('navigation', { name: 'Blocos do percurso' }).getByRole('button', { name: 'Ideação', exact: true }).click()
  await expect(summary).toContainText('2 concluídas')
  await expect(summary).toContainText('0 em curso')
})
