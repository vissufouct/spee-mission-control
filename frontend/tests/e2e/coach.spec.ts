import { expect, test } from '@playwright/test'
test('coach orienta sobre roteiro e tarefas e mantém o hub utilizável', async ({ page }, info) => {
  await page.goto('/estudante/percurso/actividades/gestor-documental')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  await page.getByRole('button', { name: 'Coach IA', exact: true }).click()
  const coach = page.getByRole('region', { name: 'Coach IA simulado' })
  await coach.getByLabel('Actividade de referência').selectOption('gestor-documental')
  await coach.getByRole('button', { name: 'Qual é a próxima tarefa?' }).click()
  await expect(coach.getByRole('log')).toContainText('Actividade:')
  await coach.getByLabel('Pergunte ao coach').fill('Explique os blocos do roteiro')
  await coach.getByRole('button', { name: 'Enviar', exact: true }).click()
  await expect(coach.getByRole('log')).toContainText('Acolhimento')
  await page.screenshot({ path: info.outputPath('coach-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(coach.getByLabel('Pergunte ao coach')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('coach-mobile.png') })
  await page.getByRole('button', { name: /Comunidade/ }).click()
  await expect(page.getByRole('textbox', { name: 'Mensagem', exact: true })).toBeVisible()
})
