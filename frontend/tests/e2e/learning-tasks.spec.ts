import { expect, test } from './legacy-fixture'
import { completeRegistrationLearningTasks } from './learning-task-helpers'

test('tarefas, quiz e materiais persistem sem conclusão por simples abertura', async ({ page }, info) => {
  await page.goto('/estudante/percurso/actividades/registar-empresa')
  const tasks = page.getByRole('region', { name: 'Tarefas da actividade' })
  await expect(tasks.getByRole('listitem')).toHaveCount(6)
  await expect(tasks.getByRole('listitem').first()).toContainText('Pré-quiz')
  await expect(tasks.getByRole('listitem').last()).toContainText('Submeter Declaração de Início de actividade')
  await expect(tasks.getByRole('listitem').last()).toContainText('Por iniciar')
  await expect(page.locator('.student-context-action')).toHaveCount(0)
  await page.getByRole('button', { name: 'Responder ao quiz: Pré-quiz de registo da empresa' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Validar respostas' }).click()
  await expect(dialog.getByRole('alert')).toHaveCount(3)
  await dialog.getByLabel('7 algarismos', { exact: true }).check()
  await dialog.getByLabel('Zero em todos os casos').check()
  await dialog.getByLabel('Abrir o formulário', { exact: true }).check()
  await dialog.getByRole('button', { name: 'Validar respostas' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Reveja as respostas')
  await page.screenshot({ path: info.outputPath('quiz-error.png') })
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.locator('.student-context-card--current')).toContainText('(1 de 6)')
  await completeRegistrationLearningTasks(page)
  await page.reload()
  await expect(page.locator('.student-context-card--current')).toContainText('(4 de 6)')
  await page.getByRole('button', { name: 'Ver respostas: Pré-quiz de registo da empresa' }).click()
  await expect(dialog.getByLabel('9 algarismos', { exact: true })).toBeChecked()
  await expect(dialog.getByLabel('9 algarismos', { exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`activity-tasks-${width}.png`), fullPage: true })
  }
})

test('vídeo e URL exigem confirmação; operação bloqueada não pode ser concluída', async ({ page }, info) => {
  await page.goto('/estudante/percurso/actividades/convidar-socios')
  await page.getByRole('button', { name: /Ver vídeo:/ }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('checkbox')).toBeDisabled()
  await dialog.locator('video').evaluate(async element => { const video = element as HTMLVideoElement; video.muted = true; video.playbackRate = 4; await video.play() })
  await expect(dialog.getByRole('checkbox')).toBeEnabled({ timeout: 15000 })
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
  await expect(dialog.getByRole('status')).toContainText('Tarefa concluída')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /Consultar página:/ }).click()
  await expect(page.frameLocator('iframe').getByRole('heading', { name: 'Responsabilidades dos sócios' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('required-url.png') })
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
  await expect(dialog.getByRole('status')).toContainText('Tarefa concluída')
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.locator('.student-context-card--current')).toContainText('(2 de 5)')
  for (const title of ['Identificar os membros da sociedade.', 'Enviar os convites aos sócios.', 'Consultar as participações confirmadas.']) {
    await page.getByRole('button', { name: `Iniciar tarefa: ${title}`, exact: true }).click()
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
    await expect(dialog.getByRole('status')).toContainText('Tarefa concluída')
    await page.keyboard.press('Escape')
  }
  await expect(page.locator('.student-context-card--current')).toContainText('(5 de 5)')
  await expect(page.locator('.student-next-activity')).toHaveCount(0)
  await page.goto('/estudante/percurso/actividades/inicio-actividades')
  await page.getByRole('button', { name: /Ver condição:/ }).first().click()
  await expect(dialog).toContainText('Requer a constituição concluída')
  await expect(dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' })).toHaveCount(0)
})
