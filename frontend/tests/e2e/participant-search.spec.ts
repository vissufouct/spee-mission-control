import { expect, test } from '@playwright/test'

test('pesquisa extensa mantém convidados entre filtros e inicia conversa privada', async ({ page }, info) => {
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-hub-social--many-participants&viewMode=story')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  const hub = page.getByRole('dialog', { name: /Hub social/ })
  await hub.getByRole('button', { name: 'Criar grupo', exact: true }).click()
  await hub.getByRole('textbox', { name: 'Nome do grupo' }).fill('Preparação do plano de negócio')
  const search = hub.getByRole('searchbox', { name: 'Pesquisar participantes por nome ou turma' })
  await expect(hub.getByRole('status')).toContainText('85 participantes encontrados')
  await expect(hub.getByRole('checkbox', { name: 'Ana Machava · Turma A' })).toHaveCount(0)
  const results = hub.getByRole('list', { name: 'Resultados da pesquisa de participantes' })
  expect(await results.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true)
  await search.fill('JOAO turma a')
  const joao = hub.getByRole('checkbox', { name: 'João Tembe · Turma A' })
  await expect(hub.getByRole('checkbox')).toHaveCount(1)
  await joao.focus()
  await joao.press('Space')
  await search.fill('turma b')
  await expect(hub.getByRole('checkbox', { name: 'João Tembe · Turma A' })).toHaveCount(0)
  await hub.getByRole('checkbox', { name: 'Leila Faife · Turma B' }).check()
  await expect(hub.getByRole('status')).toContainText('2 seleccionados')
  await hub.getByRole('button', { name: 'Retirar Leila Faife · Turma B' }).click()
  await search.fill('pessoa inexistente')
  await expect(hub.getByText('Nenhum participante encontrado. Experimente outro nome ou turma.')).toBeVisible()
  await expect(hub.getByRole('button', { name: 'Retirar João Tembe · Turma A' })).toBeVisible()
  await search.fill('fatima')
  await hub.getByRole('checkbox', { name: 'Fátima Bila · Turma A' }).check()
  await page.screenshot({ path: info.outputPath('pesquisa-grupo.png') })
  await hub.getByRole('button', { name: 'Criar e convidar' }).click()
  await expect(hub.getByText('Membros: Ana Machava · Convites pendentes: João Tembe, Fátima Bila')).toBeVisible()
  await hub.getByRole('button', { name: 'Privadas', exact: true }).click()
  await hub.getByRole('button', { name: 'Nova mensagem privada', exact: true }).click()
  await search.fill('fatima turma a')
  await hub.getByRole('button', { name: 'Conversar com Fátima Bila · Turma A' }).click()
  await expect(hub.getByRole('heading', { name: 'Fátima Bila' })).toBeVisible()
  await expect(search).toHaveCount(0)
  await hub.getByRole('button', { name: 'Nova mensagem privada', exact: true }).click()
  await search.fill('fatima bila')
  await hub.getByRole('button', { name: 'Conversar com Fátima Bila · Turma A' }).click()
  await expect(hub.locator('.social-channel-list').getByRole('button', { name: 'Fátima Bila', exact: true })).toHaveCount(1)
  await page.setViewportSize({ width: 390, height: 844 })
  await hub.getByRole('button', { name: 'Nova mensagem privada', exact: true }).click()
  await search.fill('turma c')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('pesquisa-privada-mobile.png') })
})
