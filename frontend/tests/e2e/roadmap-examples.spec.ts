import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
const activity = '/estudante/percurso/actividades/'

test('entrada, empresas isoladas e cenário preservado na navegação', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Painel do Estudante/ }).click()
  await expect(page.getByRole('link', { name: /Entrar no exemplo 2/ })).toBeVisible()
  await page.screenshot({ path: info.outputPath('entrada-exemplos.png'), fullPage: true })
  await page.getByRole('link', { name: /Entrar no exemplo 1/ }).click()
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '47')
  await expect(page.getByText(/Horizonte Verde, Lda./).first()).toBeVisible()
  await page.getByRole('button', { name: 'Ver tarefas: Constituição legal da empresa', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Tarefas da actividade' }).getByRole('listitem').filter({ hasText: 'Concluído' })).toHaveCount(4)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Tarefas da actividade' }).getByRole('listitem').filter({ hasText: 'Concluído' })).toHaveCount(4)
  await page.goto('/estudante/percurso?exemplo=2')
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '0')
  await expect(page.getByText(/Nascente Criativa/).first()).toBeVisible()
  await page.getByRole('link', { name: 'Ver percurso completo' }).click()
  await expect(page.getByText('Brevemente', { exact: true })).toBeVisible()
  await expect(page.getByText(/0 de 15 actividades concluídas/)).toBeVisible()
})

test('PDF e capa de vídeo exigem confirmação sem afectar o outro exemplo', async ({ page }, info) => {
  await page.goto(activity + 'boas-vindas?exemplo=2')
  await page.getByRole('button', { name: 'Ler PDF: Conhecer a apresentação do SPEE' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' })).toBeDisabled()
  await dialog.getByLabel('Confirmo que consultei o material obrigatório.').check()
  await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Tarefa concluída.')
  await dialog.getByRole('button', { name: 'Fechar', exact: true }).last().click()
  await page.getByRole('button', { name: 'Ver vídeo: Explorar a navegação no painel' }).click()
  await expect(dialog.getByRole('img')).toBeVisible()
  await expect(dialog.getByRole('checkbox')).toBeDisabled()
  await page.screenshot({ path: info.outputPath('capa-video.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Simular visualização' }).click()
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Tarefa concluída.')
  await page.goto('/estudante/percurso')
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '7')
  await page.goto('/estudante/percurso?exemplo=1')
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '47')
  await page.goto('/estudante/percurso?exemplo=2')
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '7')
})

test('registo, declaração e submissão de PDF com persistência', async ({ page }, info) => {
  await page.goto(activity + 'registar-empresa?exemplo=1')
  await page.getByRole('button', { name: 'Continuar tarefa: Registar a empresa' }).click()
  await page.getByRole('button', { name: 'Rever e confirmar', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar registo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Empresa registada', exact: true })).toBeVisible()
  await page.goto(activity + 'registar-empresa')
  await page.getByRole('button', { name: 'Iniciar tarefa: Declarar o início de actividades' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirmar conclusão da tarefa' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Tarefa concluída.')
  await dialog.getByRole('button', { name: 'Fechar', exact: true }).last().click()
  await page.getByRole('button', { name: 'Submeter evidência: Submeter a publicação no Boletim da República' }).click()
  await expect(dialog.getByRole('button', { name: 'Confirmar submissão' })).toBeDisabled()
  await dialog.locator('input[type=file]').setInputFiles(resolve('public/apoio/exemplo-publicacao.pdf'))
  await dialog.getByLabel(/Confirmo a submissão de exemplo-publicacao.pdf/).check()
  await dialog.getByRole('button', { name: 'Confirmar submissão' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Submetido · PDF')
  await page.screenshot({ path: info.outputPath('evidencia-submetida.png'), fullPage: true })
  await page.reload()
  await expect(page.getByRole('region', { name: 'Tarefas da actividade' }).getByRole('listitem').filter({ hasText: /Concluído|Submetido/ })).toHaveCount(7)
  await page.getByRole('button', { name: 'Ver submissão: Submeter a publicação no Boletim da República' }).click()
  await expect(dialog.getByText('exemplo-publicacao.pdf', { exact: true })).toBeVisible()
  await expect(dialog.getByRole('link').first()).toHaveAttribute('href', /^data:application\/pdf;base64,/)
})

