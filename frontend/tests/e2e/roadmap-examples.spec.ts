test('ecrã móvel sem overflow', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  for (const url of ['/estudante/percurso?exemplo=1', activity + 'registar-empresa', '/estudante/percurso/completo', '/estudante/percurso?exemplo=2']) {
    await page.goto(url)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.screenshot({ path: info.outputPath('exemplo-2-mobile.png'), fullPage: true })
})
