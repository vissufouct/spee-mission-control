import { expect, test } from '@playwright/test'
test('empresa junto ao autor abre ficha e devolve foco', async ({ page }, info) => {
  await page.goto('/estudante/percurso?exemplo=1')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  const link = page.getByRole('link', { name: 'Maputo Soluções, Lda.', exact: true }).first()
  await expect(link).toBeVisible()
  await link.click()
  const card = page.getByRole('dialog', { name: 'Maputo Soluções, Lda.', exact: true })
  await expect(card).toContainText('Leila Faife')
  await expect(card).toContainText('Turma B')
  await page.keyboard.press('Escape')
  await expect(card).not.toBeVisible()
  await expect(link).toBeFocused()
  await page.screenshot({ path: info.outputPath('company-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await link.click()
  await expect(card).toBeVisible()
  await page.screenshot({ path: info.outputPath('company-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
