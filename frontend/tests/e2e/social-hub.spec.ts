import { expect, test } from '@playwright/test'

test('comunidade, respostas, emojis, convites e mensagens privadas persistem', async ({ page }, info) => {
  await page.goto('/estudante/percurso')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  const hub = page.getByRole('dialog', { name: /Hub social/ })
  await expect(hub).toBeVisible()
  await expect(hub).toContainText('Turma B')
  await hub.getByRole('button', { name: 'Responder', exact: true }).first().click()
  await hub.getByRole('textbox', { name: 'Mensagem', exact: true }).fill('Gostei da proposta!')
  await hub.getByRole('button', { name: '😊 Emojis' }).click()
  await hub.getByRole('button', { name: 'Festa e lazer', exact: true }).click()
  await hub.getByRole('button', { name: '🎉 celebração', exact: true }).click()
  await hub.getByRole('button', { name: 'Publicar mensagem' }).click()
  await expect(hub.locator('article').last()).toContainText('Gostei da proposta!🎉')
  await expect(hub.locator('article').last()).toContainText('Em resposta a Leila Faife')
  await hub.getByRole('button', { name: /Reagir 💡 à mensagem de Ana/ }).last().click()
  await expect(hub.getByRole('button', { name: /Reagir 💡 à mensagem de Ana/ }).last()).toHaveAttribute('aria-pressed', 'true')
  await hub.getByRole('button', { name: /Grupos/ }).click()
  await hub.getByRole('button', { name: 'Aceitar convite' }).click()
  await expect(hub).toContainText('Vamos reunir as evidências neste grupo.')
  await hub.getByRole('button', { name: 'Criar grupo', exact: true }).click()
  await hub.getByRole('textbox', { name: 'Nome do grupo' }).fill('Equipa de validação')
  await hub.getByRole('checkbox', { name: 'Leila Faife · Turma B' }).check()
  await hub.getByRole('button', { name: 'Criar e convidar' }).click()
  await expect(hub).toContainText('Convites pendentes: Leila Faife')
  await hub.getByRole('button', { name: 'Privadas', exact: true }).click()
  await hub.getByRole('combobox', { name: 'Destinatário da mensagem privada' }).selectOption('leila')
  await expect(hub.getByRole('heading', { name: 'Leila Faife', exact: true })).toBeVisible()
  await hub.getByRole('textbox', { name: 'Mensagem', exact: true }).fill('Podemos rever a proposta amanhã?')
  await hub.getByRole('button', { name: 'Publicar mensagem' }).click()
  await expect(hub).toContainText('Podemos rever a proposta amanhã?')
  await page.screenshot({ path: info.outputPath('social-desktop.png') })
  await page.keyboard.press('Escape')
  await expect(hub).not.toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  await hub.getByRole('button', { name: 'Privadas', exact: true }).click()
  await hub.getByRole('button', { name: 'Leila Faife', exact: true }).click()
  await expect(hub).toContainText('Podemos rever a proposta amanhã?')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('social-mobile.png') })
  await page.goto('/docente/mission-control')
  await expect(page.getByRole('button', { name: /Abrir hub social/ })).toHaveCount(0)
})

test('pesquisa emojis e mostra configuração em falta dos GIFs', async ({ page }, info) => {
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-hub-social--with-data&viewMode=story')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  await page.getByRole('button', { name: '😊 Emojis' }).click()
  await page.getByRole('textbox', { name: 'Pesquisar emojis' }).fill('foguetao')
  await page.getByRole('button', { name: '🚀 foguetão' }).click()
  await expect(page.getByRole('textbox', { name: 'Mensagem', exact: true })).toHaveValue('🚀')
  await page.getByRole('button', { name: 'Rostos', exact: true }).click()
  await page.screenshot({ path: info.outputPath('emoji-picker.png') })
  await page.getByRole('button', { name: 'GIFs', exact: true }).click()
  await expect(page.getByText('A pesquisa de GIFs aguarda a configuração do GIPHY.')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '😊 Emojis' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('emoji-mobile.png') })
})

test('selector GIF isolado permite pré-visualizar, remover e publicar sem legenda', async ({ page }, info) => {
  // Adaptador de demonstração da story; nenhum pedido à API real.
  await page.route('https://media.giphy.com/**', route => route.fulfill({ contentType: 'image/gif', body: Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7', 'base64') }))
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-hub-social--with-gifs&viewMode=story')
  await page.getByRole('button', { name: /Abrir hub social/ }).click()
  await page.getByRole('button', { name: 'GIFs', exact: true }).click()
  await page.getByRole('button', { name: 'Seleccionar GIF: GIF de exemplo' }).click()
  await expect(page.getByRole('button', { name: 'Remover GIF' })).toBeVisible()
  await page.getByRole('button', { name: 'Remover GIF' }).click()
  await expect(page.getByRole('button', { name: 'Remover GIF' })).toHaveCount(0)
  await page.getByRole('button', { name: 'GIFs', exact: true }).click()
  await page.getByRole('textbox', { name: 'Pesquisar GIFs' }).fill('olá')
  await page.getByRole('button', { name: 'Pesquisar', exact: true }).click()
  await expect(page.getByText('Resultados para «olá»')).toBeVisible()
  await page.getByRole('button', { name: 'Seleccionar GIF: GIF de exemplo' }).click()
  await page.getByRole('button', { name: 'Publicar mensagem' }).click()
  await expect(page.locator('.social-message').last().getByRole('img', { name: 'GIF de exemplo' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('gif-sent.png') })
})
