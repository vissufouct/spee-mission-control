test('conversa com docente faz round-trip e resolução é explícita', async ({ page }, info) => {
  await page.goto(home + '/actividades/registar-empresa')
  await page.locator('.student-notification-launcher').click()
  await page.getByRole('link', { name: 'Consultar histórico da actividade' }).click()
  await page.getByLabel('Mensagem', { exact: true }).fill('Podemos confirmar o registo com estes documentos?')
  await page.getByRole('button', { name: 'Enviar mensagem', exact: true }).click()
  await expect(page.getByText('Podemos confirmar o registo com estes documentos?', { exact: true })).toBeVisible()
  await page.goto('/docente/mission-control/empresas/horizonte-verde')
  await page.getByRole('button', { name: /Pedidos de orientação/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: /Registar empresa/ }).click()
  await page.getByLabel('Resposta').fill('Sim, confirmem o NUIT e anexem o comprovativo de reserva.')
  await page.getByRole('button', { name: 'Responder', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Sim, confirmem o NUIT e anexem o comprovativo de reserva.', { exact: true })).toBeVisible()
  await page.goto(home)
  await page.locator('.student-notification-launcher').click()
  await page.getByRole('tab', { name: /Docente/ }).click()
  await page.getByRole('dialog').getByRole('listitem').filter({ hasText: 'Sim, confirmem o NUIT e anexem o comprovativo de reserva.' }).getByRole('link', { name: 'Abrir conversa' }).click()
  await expect(page.getByText('Sim, confirmem o NUIT e anexem o comprovativo de reserva.', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.screenshot({ path: info.outputPath('activity-desktop.png'), fullPage: true })
})
