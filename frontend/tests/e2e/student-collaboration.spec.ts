import { test, expect } from '@playwright/test'
import fixture from '../../src/data/student-journey.fixture.json' with { type: 'json' }
const home = '/estudante/percurso'
test('chat tabulado carrega histórico ao subir e separa rascunhos', async ({ page }) => {
  await page.addInitScript(seed => {
    const groupMessages = Array.from({ length: 45 }, (_, index) => ({ id: 'history-' + index, activityId: 'registar-empresa', author: 'João Tembe', message: 'Mensagem do histórico ' + index, createdAt: new Date(2026, 9, 20, 10, index).toISOString(), assignee: null, doneAt: null }))
    localStorage.setItem('spee.student-journey.v1', JSON.stringify({ ...seed, groupMessages }))
  }, fixture)
  await page.goto(home + '/actividades/registar-empresa?canal=group')
  const dialog = page.getByRole('dialog')
  const history = dialog.getByRole('region', { name: 'Histórico da conversa' })
  await expect(dialog.getByRole('tab', { name: 'Grupo da empresa 45' })).toHaveAttribute('aria-selected', 'true')
  await expect(history.getByRole('listitem')).toHaveCount(20)
  await expect(history.getByText('Mensagem do histórico 44', { exact: true })).toBeVisible()
  await history.evaluate(node => { node.scrollTop = 0 })
  await expect(history.getByRole('listitem')).toHaveCount(40)
  expect(await history.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  await history.evaluate(node => { node.scrollTop = 0 })
  await expect(history.getByRole('listitem')).toHaveCount(45)
  await expect(dialog.getByRole('button', { name: 'Carregar mensagens anteriores' })).toHaveCount(0)
  await dialog.getByLabel('Mensagem', { exact: true }).fill('Rascunho privado do grupo')
  await dialog.getByRole('tab', { name: /Docente/ }).click()
  await expect(dialog.getByLabel('Mensagem', { exact: true })).toHaveValue('')
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByLabel('Mensagem', { exact: true })).toHaveValue('Rascunho privado do grupo')
  await expect(dialog.getByRole('tab', { name: 'Grupo da empresa 45' })).toHaveAttribute('aria-selected', 'true')
})
test('navegar, regressar ao bloco actual e abrir actividade sem modal', async ({ page }) => {
  await page.goto(home)
  await page.getByRole('button', { name: 'Ideação', exact: true }).click()
  await expect(page).toHaveURL(/bloco=ideacao/)
  await expect(page.getByRole('heading', { name: 'Definir a ideia de negócio', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Início do percurso', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Voltar para o bloco actual', exact: true }).click()
  await expect(page).toHaveURL(/bloco=constituicao/)
  await page.getByRole('button', { name: 'Continuar Registar empresa', exact: true }).click()
  await expect(page).toHaveURL(/actividades\/registar-empresa/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: 'Percurso completo', exact: true }).click()
  await page.getByRole('link', { name: 'Ideação', exact: true }).click()
  await expect(page).toHaveURL(/bloco=ideacao/)
})
