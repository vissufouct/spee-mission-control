test('dados corrompidos mostram erro sem ferramentas de reposição', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('spee.student-journey.v1', '{invalido'))
  await page.goto(home)
  await expect(page.getByRole('alert')).toContainText('Não foi possível ler os dados locais')
  await expect(page.getByRole('button', { name: /Repor cenário/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(page.getByRole('alert')).toContainText('não foram alterados')
  expect(await page.evaluate(() => localStorage.getItem('spee.student-journey.v1'))).toBe('{invalido')
})

test('indisponibilidade do armazenamento não produz falsa confirmação', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded', 'QuotaExceededError') } })
  await page.goto(registration)
  await page.getByRole('button', { name: 'Rever e confirmar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Não foi possível guardar')
  await expect(page.getByRole('heading', { name: 'Empresa registada', exact: true })).not.toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao Meu Percurso', exact: true }).click()
  await expect(page.getByLabel('Progresso global', { exact: true })).toHaveAttribute('value', '18')
})

test('menu respeitado, percurso completo e ausência de overflow em mobile', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(home)
  await expect(page.getByRole('heading', { name: 'Meu Percurso', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('05-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Alternar menu lateral', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Gestor Documental', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Catálogo de Empresas', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'RH Online Recursos Humanos', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Roteiro de Tarefas', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Alternar menu lateral', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('link', { name: 'Ver percurso completo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Percurso completo', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto(registration)
  await expect(page.getByLabel('Denominação da empresa')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('06-formulario-mobile.png'), fullPage: true })
})
