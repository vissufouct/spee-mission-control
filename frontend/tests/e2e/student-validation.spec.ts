test('navegação estável, cartões de contexto e materiais reais do protótipo', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 700 })
  await page.goto(home)
  const navigation = page.getByRole('navigation', { name: 'Blocos do percurso' })
  await navigation.evaluate(node => node.scrollIntoView({ block: 'center' }))
  const scroll = await page.evaluate(() => scrollY)
  await navigation.getByRole('button', { name: 'Primeiro ano fiscal', exact: true }).click()
  await expect(page).toHaveURL(/bloco=primeiro-ano/)
  expect(Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThan(10)
  await navigation.getByRole('button', { name: 'Voltar para o bloco actual' }).click()
  expect(Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThan(10)
  await page.getByRole('button', { name: 'Ver tarefas: Registar empresa' }).click()
  await expect(page.getByRole('heading', { name: 'Detalhe da actividade', exact: true })).toHaveCount(0)
  const context = page.getByRole('region', { name: 'Blocos em contexto' })
  await context.getByRole('button', { name: 'Ver bloco: Constituição', exact: true }).click()
  await expect(page).toHaveURL(/percurso\?bloco=constituicao$/)
  await page.getByRole('button', { name: 'Ver tarefas: Reserva do nome', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reserva do nome', exact: true })).toHaveCount(1)
  await expect(page.getByText('Pesquisar a disponibilidade da denominação.')).toBeVisible()
  await expect(page.getByRole('link', { name: /Guia de registo da empresa/ })).toHaveCount(0)
  const popup = page.waitForEvent('popup')
  await page.locator('summary').filter({ hasText: 'Materiais de apoio' }).click()
  await page.getByRole('link', { name: /Guia de reserva do nome/ }).click()
  const resource = await popup
  await expect(resource.getByRole('heading', { name: 'Guia de reserva do nome' })).toBeVisible()
  await resource.close()
  await context.getByRole('button', { name: 'Ver bloco: Constituição', exact: true }).click()
  await page.getByRole('button', { name: 'Ver tarefas: Registar empresa', exact: true }).click()
  await page.getByRole('heading', { name: 'Registar empresa', exact: true }).click()
  await page.screenshot({ path: info.outputPath('activity-refined-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: info.outputPath('activity-refined-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
test('popup mostra pendências recentes e resolução actualiza badges', async ({ page }) => {
  await page.addInitScript(seed => {
    const groupMessages = Array.from({ length: 5 }, (_, i) => ({ id: 'pending-' + i, activityId: 'registar-empresa', author: 'João Tembe', message: 'Documento por confirmar ' + i, createdAt: new Date(2026, 9, 24, 10, i).toISOString(), assignee: null, doneAt: null }))
    localStorage.setItem('spee.roadmap-2026.1.spee.student-journey.v1', JSON.stringify({ ...seed, groupMessages, resolvedNotifications: [{ id: 'pending-4', recipient: seed.context.studentName }] }))
  }, fixture)
  await page.goto(home)
  const launcher = page.locator('.student-notification-launcher')
  await expect(launcher).toContainText('Grupo4')
  await launcher.click()
  await page.getByRole('tab', { name: 'Grupo 4', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Documento por confirmar 0')
  await expect(page.getByRole('tabpanel')).not.toContainText('Documento por confirmar 4')
  await page.getByRole('dialog').getByRole('listitem').filter({ hasText: 'Documento por confirmar 3' }).getByRole('button', { name: 'Marcar como resolvida' }).click()
  await page.keyboard.press('Escape')
  await expect(launcher).toContainText('Grupo3')
  await launcher.click()
  await expect(page.getByRole('tabpanel')).toContainText('Documento por confirmar 0')
  await expect(page.getByRole('tabpanel')).not.toContainText('Documento por confirmar 3')
})
