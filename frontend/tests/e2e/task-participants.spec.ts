import { expect, test } from '@playwright/test'

test('participantes por tarefa antes do estado, detalhes acessíveis e acções preservadas', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/estudante/percurso/actividades/registar-empresa?exemplo=1')
  const tasks = page.getByRole('region', { name: 'Tarefas da actividade' })
  const row = (title: string) => tasks.locator('.student-task-row').filter({ has: page.getByRole('heading', { name: title, exact: true }) })
  const quiz = row('Quiz sobre constituição e licenciamento')
  const reserve = row('Reservar o nome da empresa')
  const ongoing = row('Registar a empresa')
  await expect(tasks.locator('.student-task-columns')).toBeVisible()
  await expect(quiz.locator('.student-task-participants')).toHaveText('ParticipantesAna M.')
  await expect(reserve.locator('.student-task-participants')).toHaveText('ParticipantesJoão T. e António S.')
  await expect(ongoing.locator('.student-task-participants')).toHaveText('ParticipantesAna M. e João T.')
  await expect(row('Declarar o início de actividades').locator('.student-task-participants')).toContainText('—')
  await expect(page.getByRole('region', { name: 'Blocos em contexto' }).getByRole('button', { name: 'Informação sobre os participantes' })).toHaveCount(0)
  const participantsBox = (await ongoing.locator('.student-task-participants').boundingBox())!
  const statusBox = (await ongoing.getByText('Em curso', { exact: true }).boundingBox())!
  expect(participantsBox.x + participantsBox.width).toBeLessThanOrEqual(statusBox.x)
  const infoButton = reserve.getByRole('button', { name: 'Informação sobre os participantes' })
  await infoButton.hover()
  await expect(page.getByRole('tooltip')).toContainText('João Tembe')
  await expect(page.getByRole('tooltip')).toContainText('António Sitoe')
  await infoButton.click()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tooltip')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(infoButton).toBeFocused()
  await tasks.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('participantes-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await ongoing.getByRole('button', { name: 'Informação sobre os participantes' }).click()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toContainText('Ana Machava')
  await expect(tooltip).toContainText('João Tembe')
  const popupBox = (await tooltip.boundingBox())!
  expect(popupBox.x).toBeGreaterThanOrEqual(0)
  expect(popupBox.x + popupBox.width).toBeLessThanOrEqual(390)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('participantes-mobile.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await quiz.getByRole('button', { name: 'Ver respostas: Quiz sobre constituição e licenciamento' }).click()
  await expect(page.getByRole('dialog')).toContainText('Pontuação obtida: 4/4 (100%)')
  await page.goto('/estudante/percurso/actividades/registar-empresa?exemplo=2')
  await expect(tasks.locator('.student-task-row')).toHaveCount(7)
  await expect(tasks.getByRole('button', { name: 'Informação sobre os participantes' })).toHaveCount(0)
})

test('tarefas e participação funcionam isoladas do shell', async ({ page }, info) => {
  await page.goto('http://127.0.0.1:6006/iframe.html?id=estudante-tarefas-e-participantes--with-data&viewMode=story')
  await expect(page.getByRole('region', { name: 'Tarefas da actividade' })).toBeVisible()
  await expect(page.getByText('Simulador Empresarial', { exact: true })).toHaveCount(0)
  await expect(page.locator('.student-task-columns')).toBeVisible()
  await page.getByRole('button', { name: 'Informação sobre os participantes' }).first().click()
  await expect(page.getByRole('tooltip')).toContainText('Ana Machava')
  await page.screenshot({ path: info.outputPath('participantes-sem-shell.png'), fullPage: true })
})
