async function fillOrientation(page: Page, subject: string) {
  await page.getByRole('button', { name:'Nova orientação', exact:true }).click()
  await page.getByLabel('Assunto', { exact:true }).fill(subject)
  await page.getByLabel('Orientação', { exact:true }).fill('Rever os valores de IVA e anexar o apuramento.')
  await page.getByLabel('Motivo', { exact:true }).fill('Foram identificadas diferenças no apuramento.')
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho guardado')
}
test('orientação: validação, edição, persistência, eliminação e registo imutável', async ({ page }, info) => {
  await page.goto(company)
  await page.getByRole('button', { name:'Nova orientação', exact:true }).click()
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByLabel('Motivo', { exact:true })).toHaveAttribute('aria-invalid','true')
  await page.getByRole('button', { name:'Cancelar', exact:true }).click()
  await fillOrientation(page,'Rever declaração de IVA')
  await page.reload()
  await expect(page.getByText('Rever declaração de IVA', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Editar', exact:true }).click()
  await page.getByLabel('Assunto', { exact:true }).fill('Rever declaração de IVA — prioridade')
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho guardado')
  await page.getByRole('button', { name:'Eliminar', exact:true }).click()
  await page.getByRole('button', { name:'Cancelar', exact:true }).click()
  await expect(page.getByText('Rever declaração de IVA — prioridade', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Eliminar', exact:true }).click()
  await page.getByRole('button', { name:'Confirmar eliminação', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho eliminado')
  await fillOrientation(page,'Confirmar elementos de suporte')
  await page.getByRole('button', { name:'Publicar orientação', exact:true }).click()
  await page.getByRole('button', { name:'Confirmar publicação', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('publicada no cenário local')
  await expect(page.getByRole('button', { name:'Editar', exact:true })).toHaveCount(0)
  await page.getByText('Histórico das orientações (5)', { exact:true }).click()
  await expect(page.getByText('Rascunho eliminado', { exact:true })).toBeVisible()
  await page.screenshot({ path:info.outputPath('teacher-orientation.png'), fullPage:true })
  await page.reload()
  await expect(page.getByText('Publicada no cenário', { exact:true })).toBeVisible()
  await expect(page.locator('.teacher-metrics')).toContainText('47%')
})

