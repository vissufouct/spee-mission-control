import { test, expect, type Page } from '@playwright/test'
const home = '/docente/mission-control'
const company = home + '/empresas/nova-geracao'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  errors.set(page, [])
  page.on('pageerror', error => errors.get(page)!.push(error.message))
})
test.afterEach(async ({ page }) => expect(errors.get(page)).toEqual([]))

test('matriz, filtros AND, detalhe, evidência e regresso com filtros preservados', async ({ page }, info) => {
  await page.setViewportSize({ width:1607,height:979 })
  await page.goto(home)
  await expect(page.getByRole('heading', { name:'Mission Control do Docente', exact:true })).toBeVisible()
  await expect(page.getByRole('navigation', { name:'Navegação principal' }).locator('a,button')).toHaveCount(13)
  await expect(page.locator('.teacher-matrix tbody tr')).toHaveCount(8)
  await page.screenshot({ path:info.outputPath('teacher-overview.png'), fullPage:false })
  await page.getByLabel('Filtrar Constituição', { exact:true }).selectOption('completed')
  await page.getByLabel('Filtrar Salários', { exact:true }).selectOption('in-progress')
  await expect(page.locator('.teacher-matrix tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name:'Nova Geração, Lda.', exact:true }).click()
  await expect(page.getByRole('heading', { name:'Percurso da empresa', exact:true }).first()).toBeVisible()
  await page.screenshot({ path:info.outputPath('teacher-company.png'), fullPage:false })
  const view = page.getByRole('button', { name:'Ver Comprar mercadorias', exact:true })
  await view.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name:'Comprar mercadorias', exact:true })).toBeVisible()
  await dialog.getByRole('button', { name:'Compra CP-011 →', exact:true }).click()
  await expect(dialog.getByText('SIMULAÇÃO LOCAL — SEM VALIDADE OFICIAL', { exact:true })).toBeVisible()
  await page.screenshot({ path:info.outputPath('teacher-evidence.png'), fullPage:false })
  await page.keyboard.press('Escape')
  await expect(view).toBeFocused()
  await page.getByRole('link', { name:'← Voltar à turma', exact:true }).click()
  await expect(page.getByLabel('Filtrar Salários', { exact:true })).toHaveValue('in-progress')
  await expect(page.locator('.teacher-matrix tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name:'Limpar filtros', exact:true }).click()
  await page.getByLabel('Pesquisar empresa ou estudante', { exact:true }).fill('empresa inexistente')
  await expect(page.getByText('Nenhuma empresa corresponde aos filtros.')).toBeVisible()
  await page.getByRole('button', { name:'Limpar filtros', exact:true }).first().click()
  await page.getByRole('combobox', { name:'Turma', exact:true }).selectOption('turma-b')
  await expect(page.locator('.teacher-matrix tbody tr')).toHaveCount(2)
  await page.getByRole('button', { name:/Actividades com alertas/ }).click()
  await expect(page).toHaveURL(/turma=turma-b.*alertas=1/)
})

test('contribuição humana, colectiva e automática são consultas distintas', async ({ page }, info) => {
  await page.setViewportSize({ width:1607,height:979 })
  await page.goto(company)
  await page.getByRole('button', { name:'Contribuição e pista de actividade', exact:true }).click()
  await expect(page.getByRole('heading', { name:'Contribuição e pista de actividade', exact:true })).toBeVisible()
  await page.screenshot({ path:info.outputPath('teacher-contributions.png'), fullPage:false })
  const humanRows = await page.locator('.teacher-contributions tbody tr').count()
  await page.getByRole('button', { name:'Acções colectivas', exact:true }).click()
  await expect(page.getByRole('button', { name:'Acções colectivas', exact:true })).toHaveAttribute('aria-pressed','true')
  expect(await page.locator('.teacher-contributions tbody tr').count()).toBeLessThan(humanRows)
  await page.getByRole('button', { name:'Eventos automáticos', exact:true }).click()
  await expect(page.locator('.teacher-contributions tbody tr')).toHaveCount(1)
  await expect(page.getByText('Os eventos automáticos não são atribuídos a estudantes.')).toBeVisible()
  await page.getByRole('link', { name:'← Voltar ao percurso', exact:true }).click()
  await expect(page).toHaveURL(new RegExp(company + '$'))
})

async function fillOrientation(page: Page, subject: string) {
  await page.getByRole('button', { name:'Nova orientação', exact:true }).click()
  await page.getByLabel('Assunto', { exact:true }).fill(subject)
  await page.getByLabel('Orientação', { exact:true }).fill('Rever os valores de IVA e anexar o apuramento.')
  await page.getByLabel('Motivo', { exact:true }).fill('Foram identificadas diferenças no apuramento.')
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho guardado')
}
test('orientação: validação, edição, persistência, eliminação e registo imutável', async ({ page }, info) => {
  await page.goto(company)
  await page.getByRole('button', { name:'Nova orientação', exact:true }).click()
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByLabel('Motivo', { exact:true })).toHaveAttribute('aria-invalid','true')
  await page.getByRole('button', { name:'Cancelar', exact:true }).click()
  await fillOrientation(page,'Rever declaração de IVA')
  await page.reload()
  await expect(page.getByText('Rever declaração de IVA', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Editar', exact:true }).click()
  await page.getByLabel('Assunto', { exact:true }).fill('Rever declaração de IVA — prioridade')
  await page.getByRole('button', { name:'Guardar rascunho', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho guardado')
  await page.getByRole('button', { name:'Eliminar', exact:true }).click()
  await page.getByRole('button', { name:'Cancelar', exact:true }).click()
  await expect(page.getByText('Rever declaração de IVA — prioridade', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Eliminar', exact:true }).click()
  await page.getByRole('button', { name:'Confirmar eliminação', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Rascunho eliminado')
  await fillOrientation(page,'Confirmar elementos de suporte')
  await page.getByRole('button', { name:'Registar orientação', exact:true }).click()
  await page.getByRole('button', { name:'Confirmar registo local', exact:true }).click()
  await expect(page.getByRole('status')).toContainText('Não foi enviada qualquer mensagem')
  await expect(page.getByRole('button', { name:'Editar', exact:true })).toHaveCount(0)
  await page.getByText('Histórico das orientações (5)', { exact:true }).click()
  await expect(page.getByText('Rascunho eliminado', { exact:true })).toBeVisible()
  await page.screenshot({ path:info.outputPath('teacher-orientation.png'), fullPage:true })
  await page.reload()
  await expect(page.getByText('Registada · só consulta', { exact:true })).toBeVisible()
  await expect(page.locator('.teacher-metrics')).toContainText('47%')
})

